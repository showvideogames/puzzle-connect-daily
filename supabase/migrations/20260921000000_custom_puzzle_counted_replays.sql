-- ---------------------------------------------------------------------------
-- 5. get_custom_puzzle_stats -- aggregates only, from the counter row
--
-- Always returns all five buckets. completed_plays = wins + losses. The
-- average is over wins only. finished_plays is kept as an alias for clients
-- cached from before this migration.
-- ---------------------------------------------------------------------------
create or replace function public.get_custom_puzzle_stats(_share_id text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  _cpid uuid;
  s     public.custom_puzzle_stats%rowtype;
begin
  select id into _cpid
    from public.custom_puzzles
   where share_id = _share_id
     and moderation_status = 'active';

  if _cpid is null then
    return null;
  end if;

  select * into s from public.custom_puzzle_stats where custom_puzzle_id = _cpid;

  return jsonb_build_object(
    'completed_plays', coalesce(s.wins, 0) + coalesce(s.losses, 0),
    'finished_plays',  coalesce(s.wins, 0) + coalesce(s.losses, 0),
    'wins',            coalesce(s.wins, 0),
    'losses',          coalesce(s.losses, 0),
    'avg_guesses',     case when coalesce(s.wins, 0) > 0
                            then round(s.win_guess_total::numeric / s.wins, 2)
                            else 0 end,
    'guess_distribution', jsonb_build_object(
      '4',  coalesce(s.guesses_4, 0),
      '5',  coalesce(s.guesses_5, 0),
      '6',  coalesce(s.guesses_6, 0),
      '7',  coalesce(s.guesses_7, 0),
      '8+', coalesce(s.guesses_8_plus, 0)
    )
  );
end;
$$;

comment on function public.get_custom_puzzle_stats(text) is
  'Aggregate completed-play stats for one custom puzzle (by share_id, so Private stats require possessing the link): completed plays, wins, losses, average guesses over wins, and the fixed 4/5/6/7/8+ distribution. Never returns anything row-level.';

-- ---------------------------------------------------------------------------
-- 6. get_creator_profile -- "plays" now means completed plays (wins + losses),
--    not the number of distinct devices. Otherwise identical to the version
--    in 20260920000000.
-- ---------------------------------------------------------------------------
create or replace function public.get_creator_profile(_slug text, _sort text default 'newest')
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  _uid   uuid;
  _name  text;
  _s     text := case when _sort in ('newest', 'plays', 'favorites') then _sort else 'newest' end;
begin
  select user_id, display_name into _uid, _name
    from public.creator_profiles
   where public_slug = _slug;
  if _uid is null then
    return null;
  end if;

  return (
    with pub as (
      select cp.title,
             cp.content ->> 'mode' as mode,
             cp.short_code,
             (select coalesce(s.wins + s.losses, 0) from public.custom_puzzle_stats s where s.custom_puzzle_id = cp.id) as plays,
             (select count(*) from public.custom_puzzle_favorites f where f.custom_puzzle_id = cp.id) as favs,
             cp.created_at
        from public.custom_puzzles cp
       where cp.created_by = _uid
         and cp.visibility = 'public'
         and cp.moderation_status = 'active'
    )
    select jsonb_build_object(
      'display_name',    _name,
      'public_slug',     _slug,
      'puzzle_count',    (select count(*) from pub),
      'total_plays',     (select coalesce(sum(plays), 0) from pub),
      'total_favorites', (select coalesce(sum(favs), 0) from pub),
      'puzzles',         coalesce((
        select jsonb_agg(
                 jsonb_build_object(
                   'title',          q.title,
                   'mode',           q.mode,
                   'short_code',     q.short_code,
                   'finished_plays', q.plays,
                   'favorite_count', q.favs,
                   'created_at',     q.created_at
                 )
                 order by (case _s when 'plays' then q.plays end) desc nulls last,
                          (case _s when 'favorites' then q.favs end) desc nulls last,
                          q.created_at desc)
          from (select * from pub
                 order by (case _s when 'plays' then plays end) desc nulls last,
                          (case _s when 'favorites' then favs end) desc nulls last,
                          created_at desc
                 limit 100) q
      ), '[]'::jsonb)
    )
  );
end;
$$;

revoke all on function public.get_creator_profile(text, text) from public;
grant execute on function public.get_creator_profile(text, text) to anon, authenticated, service_role;

comment on function public.get_creator_profile(text, text) is
  'Public creator page data: display name, totals and the creator''s Public, non-moderated puzzles only (sort: newest | plays | favorites). Returns only explicitly listed safe fields.';
