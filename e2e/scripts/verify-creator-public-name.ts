/** Isolated PostgreSQL check: node --experimental-strip-types e2e/scripts/verify-creator-public-name.ts */
import assert from "node:assert/strict";
import { PGlite } from "@electric-sql/pglite";
import { buildSchemaPlan, applySchemaPlan } from "./lib/schema.ts";

const db = new PGlite();
type Name = { display_name?: string; next_change_at?: string | null; chosen?: boolean; outcome: string };
type Puzzle = { puzzle_id: string; share_id: string; short_code: string };
const rows = ["ALTO BASS SOPRANO TENOR", "BALLAD HYMN LULLABY SHANTY", "CASSETTE RECORD REEL VINYL", "ENCORE GIG SETLIST TOUR"].map(line => line.split(" "));
const content = JSON.stringify({ mode: "classic", groups: rows.map((words, i) => ({ category: "Fixture Group " + i, words })), word_order: rows.flat(), rainbow_herring: null });
const auth = async (uid: string | null, role = "authenticated") => {
  await db.exec("reset role");
  await db.query("select set_config('request.jwt.claims',$1,false)", [uid ? JSON.stringify({sub: uid, role}) : ""]);
  if (uid || role === "anon") await db.exec("set role " + role);
};
const account = async (ensure = true) => {
  await auth(null);
  const id = (await db.query<{id:string}>("insert into auth.users default values returning id")).rows[0].id;
  const sub = "user_" + id.replaceAll("-", "");
  await db.query("insert into auth.identities(user_id,provider,provider_id,identity_data) values ($1,'custom:platform',$2,$3::jsonb)", [id, sub, JSON.stringify({sub})]);
  if (ensure) { await auth(id); await db.query("select * from public.ensure_account()"); }
  return id;
};
const call = async <T>(query: string, values: unknown[] = []) => (await db.query<{r:T}>("select " + query + " as r", values)).rows[0].r;
const read = () => call<Name>("public.get_my_creator_name()");
const name = (v: string) => call<Name>("public.set_my_creator_name($1)", [v]);
const create = (designer: string, title: string) => call<Puzzle>("public.create_custom_puzzle($1,$2,'public',$3::jsonb)", [designer, title, content]);
const board = (short: string) => call<{ creator_name: string }>("public.get_custom_puzzle_by_short_code($1)", [short]);
try {
  const plan = buildSchemaPlan({includeSupabaseStubs:true, includeReset:false});
  await applySchemaPlan(db, plan.slice(0,-1));
  const legacy = await account();
  const oldBoard = await create("Early Screenname", "First mixtape");
  const fresh = await account();
  const implicit = await account();
  const unlinked = await account(false);
  await auth(null);
  const slug = (await db.query<{public_slug:string}>("select public_slug from public.creator_profiles where user_id=$1",[legacy])).rows[0].public_slug;
  const before = (await db.query("select to_jsonb(p) from public.custom_puzzles p order by id")).rows;
  await applySchemaPlan(db, plan.slice(-1));
  assert.deepEqual((await db.query("select to_jsonb(p) from public.custom_puzzles p order by id")).rows,before);
  await auth(null,"anon");
  await assert.rejects(read(), /permission denied/);
  await assert.rejects(name("Guest"), /permission denied/);
  await auth(unlinked);
  await assert.rejects(read(), /sign in/);
  await assert.rejects(name("Unlinked"), /sign in/);
  await auth(fresh);
  assert.deepEqual(await read(), { display_name:null, next_change_at:null, chosen:false,outcome:"ready" });
  assert.equal((await name("x".repeat(61))).outcome,"invalid");
  assert.equal((await name("   ")).outcome,"invalid");
  assert.equal((await name("fixture@example.test")).outcome,"invalid");
  assert.equal((await name("Unsafe\u202EName")).outcome,"invalid");
  assert.deepEqual(await name("  José   Rivera  "), {display_name:"José Rivera", next_change_at:null, chosen:true,outcome:"saved"});
  assert.equal((await name("José Rivera")).next_change_at,null,"no-op does not start cooldown");
  await assert.rejects(db.query("select * from public.creator_name_choices"), /permission denied/);
  await auth(null);
  assert.deepEqual((await db.query("select * from public.creator_profiles where user_id=$1",[fresh])).rows,[]);
  await auth(fresh);
  const firstRename = await name("Cactus42");
  assert.ok(firstRename.next_change_at);
  assert.equal(firstRename.outcome,"saved");
  assert.equal((await name("  Cactus42 ")).next_change_at,firstRename.next_change_at,"no-op does not restart cooldown");
  assert.deepEqual(await name("New Choice"), {...firstRename,outcome:"cooldown"});
  await auth(null);
  await db.query("update public.creator_name_choices set last_renamed_at=now()-interval '720 hours 1 second' where user_id=$1",[fresh]);
  await auth(fresh);
  assert.equal((await name("New Choice")).outcome,"saved");
  const ownBoard = await create("Stale draft credit","Second mixtape");
  assert.equal((await board(ownBoard.short_code)).creator_name,"New Choice","create enforces the public name even from an older client");
  await auth(implicit);
  await assert.rejects(create("invalid@example.test","Unsafe initial name"), /not an email/);
  assert.equal((await board((await create("  First   Credit ", "First signed-in board")).short_code)).creator_name,"First Credit");
  assert.deepEqual(await read(),{display_name:"First Credit",next_change_at:null,chosen:true,outcome:"ready"});
  assert.equal((await board((await create("Try a different byline", "Second signed-in board")).short_code)).creator_name,"First Credit");
  assert.equal((await name("New Credit")).outcome,"saved");
  assert.equal((await name("Third Credit")).outcome,"cooldown");
  await auth(legacy);
  assert.deepEqual(await read(),{display_name:"Early Screenname",next_change_at:null,chosen:false,outcome:"ready"});
  const legacyRename=await name("New Choice");
  assert.equal(legacyRename.outcome,"saved","legacy name can rename immediately and need not be unique");
  assert.ok(legacyRename.next_change_at);
  assert.equal((await name("Third Choice")).outcome,"cooldown");
  await auth(null);
  assert.equal((await board(oldBoard.short_code)).creator_name,"Early Screenname","legacy byline is unchanged");
  assert.deepEqual((await db.query("select public_slug,display_name from public.creator_profiles where user_id=$1",[legacy])).rows,[{public_slug:slug,display_name:"New Choice"}]);
  assert.deepEqual((await db.query("select to_jsonb(p) from public.custom_puzzles p where id=$1",[oldBoard.puzzle_id])).rows,before);
  await auth(null,"anon");
  const guest = await create("Guest Credit","Guest board");
  assert.equal((await board(guest.short_code)).creator_name,"Guest Credit");
  await auth(null);
  console.log("Passed: full migration, first choice vs rename, legacy rename, no-ops, 720-hour expiry, isolated accounts and defenses, stable slug and legacy puzzle row, shared future byline and guest compatibility.");
} finally { await db.close(); }
